def _surface_expectations(row: dict[str, Any]) -> dict[str, dict[str, Any]]:
    """Expand shared declaration facts into every named delivery surface."""
    result: dict[str, dict[str, Any]] = {}
    for surface in ("help", "bash", "zsh", "smartbar", "tui"):
        spelling = row["cli_spelling"]
        if row["hidden"] and surface != "tui":
            spelling = ()
        result[surface] = {
            "spelling": spelling,
            "required": row["required"] if spelling else False,
            "delivered_type": row["delivered_type"] if spelling else None,
        }
    for surface in ("info", "mcp", "http", "lambda"):
        spelling = row["wire_spelling"]
        result[surface] = {
            "spelling": spelling,
            "required": row["required"] if spelling else False,
            "delivered_type": row["delivered_type"] if spelling else None,
        }
    return result


ROWS: tuple[dict[str, Any], ...] = tuple(
    {**row, "surfaces": _surface_expectations(row)} for row in _RAW_ROWS
)


def module_source(row: dict[str, Any], *, future_annotations: bool = False) -> str:
    """Compile-ready job module for either annotation evaluation mode."""
    prefix = "from __future__ import annotations\n" if future_annotations else ""
    return prefix + HEADER + row["declaration_source"]
