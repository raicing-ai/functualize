"""The cross-repo contract: this port reproduces the frozen vectors.

``vectors.json`` is copied verbatim from the FuncCloud reference
implementation (funccloud ``packages/vault-crypto/vectors/vectors.json``,
sha256 ``7eed69b0…eef``) and generated by its TypeScript side; the
reference Python and this vendored port must both reproduce it
byte-identically. That reproduction — plus every fail-closed case below —
is the merge blocker for the vault-remote feature: it is what proves two
independently-written implementations agree on the wire format, so a
protocol break cannot hide behind green local tests.
"""

from __future__ import annotations

import base64
import copy
import hashlib
import json
import os
from collections.abc import Callable
from pathlib import Path
from typing import Any

import pytest

from functualize.app.vault_remote import (
    AuthenticationFailed,
    canonical,
    decode_fragment_key,
    decode_master_key,
    ec_key_from_jwk,
    ec_scalar_to_pub_point,
    encode_fragment_key,
    encode_master_key,
    new_key,
    open_envelope,
    seal_envelope,
    unwrap_cek,
    wrap_cek_for,
)

_VECTORS_PATH = Path(__file__).parent / "vectors.json"
_VECTORS_SHA256 = (
    "7eed69b024a56ee4c3eaa14ef8c872285d8995895153ca68fbeeeeb4b5be1eef"
)

V = json.loads(_VECTORS_PATH.read_text())
KEY = base64.b64decode(V["aead_key_b64"])


def _envelope() -> dict[str, Any]:
    """A fresh copy of the vector envelope, safe to tamper with."""
    return copy.deepcopy(V["fragment_envelope"])


def _expect_auth_failed(fn: Callable[[], Any]) -> None:
    with pytest.raises(AuthenticationFailed):
        fn()


class TestVectorsFile:
    def test_file_is_the_verbatim_frozen_copy(self) -> None:
        """A regenerated or edited vectors file must be loud, not subtle —
        regeneration is a review-gate event on the funccloud side."""
        assert hashlib.sha256(_VECTORS_PATH.read_bytes()).hexdigest() == (
            _VECTORS_SHA256
        )


class TestFragmentKeyStrings:
    def test_vector_string_decodes_to_the_vector_key(self) -> None:
        assert decode_fragment_key(V["fragment_string"]) == KEY

    def test_vector_string_survives_a_round_trip(self) -> None:
        assert encode_fragment_key(decode_fragment_key(V["fragment_string"])) == (
            V["fragment_string"]
        )

    def test_master_key_string_round_trips(self) -> None:
        key = new_key()
        assert decode_master_key(encode_master_key(key)) == key


class TestKeyStringRefusals:
    def test_fragment_key_refuses_a_wrong_prefix(self) -> None:
        with pytest.raises(ValueError):
            decode_fragment_key("m1." + V["fragment_string"][3:])

    def test_fragment_key_refuses_a_wrong_length(self) -> None:
        short = base64.urlsafe_b64encode(b"\x00" * 31).rstrip(b"=").decode()
        with pytest.raises(ValueError):
            decode_fragment_key("k1." + short)

    def test_master_key_refuses_a_wrong_prefix(self) -> None:
        with pytest.raises(ValueError):
            decode_master_key(V["fragment_string"])


class TestCanonical:
    def test_canonical_vector(self) -> None:
        assert canonical(V["canonical"]["input"]) == V["canonical"]["expected"]

    def test_rejects_non_integer_numbers(self) -> None:
        with pytest.raises(ValueError):
            canonical({"x": 1.5})

    def test_rejects_nulls(self) -> None:
        with pytest.raises(ValueError):
            canonical({"x": None})

    def test_rejects_unsupported_types(self) -> None:
        with pytest.raises(ValueError):
            canonical({"x": b"bytes"})  # type: ignore[dict-item]


class TestVectorReproduction:
    def test_seal_reproduces_the_vector_byte_identically(self) -> None:
        items = [
            {"name": it["name"], "kind": it["kind"], "value": value}
            for it, value in zip(
                V["fragment_envelope"]["items"],
                V["opened_values"],
                strict=True,
            )
        ]
        envelope = seal_envelope(
            "fragment",
            V["fragment_envelope"]["metadata"],
            items,
            KEY,
            nonces=[
                base64.b64decode(it["nonce"])
                for it in V["fragment_envelope"]["items"]
            ],
        )
        assert envelope == V["fragment_envelope"]

    def test_open_returns_the_original_values(self) -> None:
        opened = open_envelope(V["fragment_envelope"], KEY)
        assert [o["value"] for o in opened] == V["opened_values"]


class TestFailClosedFragment:
    """Every tamper is one indistinguishable AuthenticationFailed.

    The parametrized names say what was altered; the assertion never
    distinguishes how the tamper was caught, and no production code may
    either.
    """

    def test_wrong_key(self) -> None:
        _expect_auth_failed(lambda: open_envelope(V["fragment_envelope"], b"\x01" * 32))

    def test_tampered_ciphertext(self) -> None:
        bad = _envelope()
        raw = bytearray(base64.b64decode(bad["items"][0]["ct"]))
        raw[0] ^= 1
        bad["items"][0]["ct"] = base64.b64encode(bytes(raw)).decode()
        _expect_auth_failed(lambda: open_envelope(bad, KEY))

    def test_truncated_ciphertext(self) -> None:
        bad = _envelope()
        raw = base64.b64decode(bad["items"][0]["ct"])
        bad["items"][0]["ct"] = base64.b64encode(raw[:10]).decode()
        _expect_auth_failed(lambda: open_envelope(bad, KEY))

    def test_tampered_nonce(self) -> None:
        bad = _envelope()
        raw = bytearray(base64.b64decode(bad["items"][0]["nonce"]))
        raw[0] ^= 1
        bad["items"][0]["nonce"] = base64.b64encode(bytes(raw)).decode()
        _expect_auth_failed(lambda: open_envelope(bad, KEY))

    def test_expiry_extension(self) -> None:
        bad = _envelope()
        bad["metadata"]["expires_at"] = "2027-01-01T00:00:00Z"
        _expect_auth_failed(lambda: open_envelope(bad, KEY))

    def test_tampered_created_at(self) -> None:
        bad = _envelope()
        bad["metadata"]["created_at"] = "2020-01-01T00:00:00Z"
        _expect_auth_failed(lambda: open_envelope(bad, KEY))

    def test_tampered_label(self) -> None:
        bad = _envelope()
        bad["metadata"]["labels"] = ["production"]
        _expect_auth_failed(lambda: open_envelope(bad, KEY))

    def test_swapped_item_names(self) -> None:
        bad = _envelope()
        a, b = bad["items"][0], bad["items"][1]
        a["name"], b["name"] = b["name"], a["name"]
        _expect_auth_failed(lambda: open_envelope(bad, KEY))

    def test_tampered_kind(self) -> None:
        bad = _envelope()
        bad["items"][0]["kind"] = "config"
        _expect_auth_failed(lambda: open_envelope(bad, KEY))

    def test_cross_share_fragment(self) -> None:
        """The link's key for share A must not open share B's bundle."""
        bad = _envelope()
        bad["metadata"]["share_id"] = "0" * 32
        _expect_auth_failed(lambda: open_envelope(bad, KEY))

    def test_version_change(self) -> None:
        bad = _envelope()
        bad["v"] = 2
        _expect_auth_failed(lambda: open_envelope(bad, KEY))

    def test_missing_version(self) -> None:
        bad = _envelope()
        del bad["v"]
        _expect_auth_failed(lambda: open_envelope(bad, KEY))

    def test_version_as_string(self) -> None:
        bad = _envelope()
        bad["v"] = "1"
        _expect_auth_failed(lambda: open_envelope(bad, KEY))

    def test_unknown_mode(self) -> None:
        bad = _envelope()
        bad["mode"] = "recipient"
        _expect_auth_failed(lambda: open_envelope(bad, KEY))


class TestEnvelopeProperties:
    def test_item_order_is_not_authenticated(self) -> None:
        """A documented property, not an oversight: the AAD binds each
        item's name/kind, never its position. Reordering a bundle is
        visible to the receiver (items come back in envelope order) but
        cannot inject or alter a value."""
        bad = _envelope()
        bad["items"].reverse()
        opened = open_envelope(bad, KEY)
        assert sorted(o["value"] for o in opened) == sorted(V["opened_values"])

    def test_empty_items_round_trip(self) -> None:
        sealed = seal_envelope(
            "fragment", V["fragment_envelope"]["metadata"], [], KEY
        )
        assert open_envelope(sealed, KEY) == []

    def test_seal_refuses_a_short_key(self) -> None:
        with pytest.raises(ValueError):
            seal_envelope("fragment", {}, [], b"\x01" * 16)


class TestMasterMode:
    def test_master_round_trip(self) -> None:
        metadata = {
            "labels": [],
            "created_at": "2026-09-24T00:00:00Z",
            "expires_at": "2026-10-24T00:00:00Z",
            "scope": "personal",
        }
        sealed = seal_envelope(
            "master",
            metadata,
            [{"name": "github_pat", "kind": "secret", "value": "ghp_x"}],
            KEY,
        )
        assert [o["value"] for o in open_envelope(sealed, KEY)] == ["ghp_x"]


class TestRecipientWrapping:
    def test_unwrap_reproduces_the_vector_cek(self) -> None:
        private = ec_key_from_jwk(V["recipient"]["private_jwk"])
        assert unwrap_cek(V["recipient"]["wrap"], private).hex() == (
            V["recipient"]["cek_hex"]
        )

    def test_vector_jwk_matches_its_public_point(self) -> None:
        d = base64.urlsafe_b64decode(V["recipient"]["private_jwk"]["d"] + "==")
        assert ec_scalar_to_pub_point(int.from_bytes(d, "big")) == (
            V["recipient"]["public_point_b64"]
        )

    def test_fresh_wrap_round_trips(self) -> None:
        cek = bytes(range(32))
        wrap = wrap_cek_for(cek, V["recipient"]["public_point_b64"], "kid-x")
        private = ec_key_from_jwk(V["recipient"]["private_jwk"])
        assert unwrap_cek(wrap, private) == cek


class TestFailClosedRecipient:
    def _private(self) -> Any:
        return ec_key_from_jwk(V["recipient"]["private_jwk"])

    def test_wrong_recipient_key(self) -> None:
        d = base64.urlsafe_b64encode(b"\x02" + b"\x00" * 30 + b"\x01")
        other = ec_key_from_jwk(
            {**V["recipient"]["private_jwk"], "d": d.rstrip(b"=").decode()}
        )
        _expect_auth_failed(lambda: unwrap_cek(V["recipient"]["wrap"], other))

    def test_tampered_kid(self) -> None:
        bad = {**V["recipient"]["wrap"], "recipient_kid": "kid-other"}
        _expect_auth_failed(lambda: unwrap_cek(bad, self._private()))

    def test_tampered_salt(self) -> None:
        bad = {
            **V["recipient"]["wrap"],
            "salt": base64.b64encode(os.urandom(32)).decode(),
        }
        _expect_auth_failed(lambda: unwrap_cek(bad, self._private()))

    def test_substituted_epk(self) -> None:
        """A valid point that is not the sender's ephemeral key derives a
        different KEK — the wrap fails as one class, like everything else."""
        bad = {
            **V["recipient"]["wrap"],
            "epk": ec_scalar_to_pub_point(0x2ADD55E1D3F5B7),
        }
        _expect_auth_failed(lambda: unwrap_cek(bad, self._private()))

    def test_tampered_wrap_nonce(self) -> None:
        raw = bytearray(base64.b64decode(V["recipient"]["wrap"]["nonce"]))
        raw[0] ^= 1
        bad = {
            **V["recipient"]["wrap"],
            "nonce": base64.b64encode(bytes(raw)).decode(),
        }
        _expect_auth_failed(lambda: unwrap_cek(bad, self._private()))

    def test_truncated_wrap_ct(self) -> None:
        raw = base64.b64decode(V["recipient"]["wrap"]["ct"])
        bad = {
            **V["recipient"]["wrap"],
            "ct": base64.b64encode(raw[:10]).decode(),
        }
        _expect_auth_failed(lambda: unwrap_cek(bad, self._private()))
